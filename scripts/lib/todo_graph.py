# One graph call's answers (D03 T01 §12): every git command and todo/plan.json read inside a `graph` call runs once,
# and the answers are dropped when the call returns or raises, so a commit or a configuration change made between two
# calls (a stamp's own writes, then its validation) is always read fresh. None: no graph call is running.
_RUN_CACHE = None
CACHE_RUNS = True  # tests switch it off to compare a cached run with an uncached one


def _git(root, *args, timeout=60):
    """`git -C root <args>`, its output as bytes; inside a graph call each distinct command runs once, a file read at
    a commit (`show <rev>:<path>`) goes through one `cat-file --batch` process, and `merge-base --is-ancestor` between
    two commits of the repository is answered from one read of its history."""
    key = (str(root), args)
    if _RUN_CACHE is not None and key in _RUN_CACHE["git"]:
        return _RUN_CACHE["git"][key]
    out = None
    if _RUN_CACHE is not None:
        if len(args) == 2 and args[0] == "show" and ":" in args[1]:
            out = _batch_show(root, args[1], timeout)
        elif len(args) == 4 and args[:2] == ("merge-base", "--is-ancestor"):
            out = _from_history(root, args[2], args[3], timeout)
    if out is None:
        out = subprocess.run(["git", "-C", str(root), *args], capture_output=True, timeout=timeout)
    if _RUN_CACHE is not None:
        _RUN_CACHE["git"][key] = out
    return out


def _batch_show(root, spec, timeout):
    """`git show <rev>:<path>` for a file, read through the graph call's one `git cat-file --batch`; None (run git
    itself) for anything that is not a file there, so a tree, a missing path or a bad name answers as `show` does.
    A reply that does not come within `timeout`, or comes short of the size it announced, retires the batch process
    and is answered by git itself, so a stalled or dying process never turns into a hang or a truncated file."""
    batches = _RUN_CACHE["batch"]
    entry = batches.get(str(root))
    if entry is None:
        proc = subprocess.Popen(["git", "-C", str(root), "cat-file", "--batch"], stdin=subprocess.PIPE,
                                stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        replies = queue.Queue()
        reader = threading.Thread(target=_batch_reader, args=(proc, replies), daemon=True)
        reader.start()
        entry = batches[str(root)] = {"proc": proc, "replies": replies, "reader": reader, "broken": False}
    if "\n" in spec or entry["broken"]:
        return None
    try:
        entry["proc"].stdin.write(spec.encode("utf-8") + b"\n")
        entry["proc"].stdin.flush()
        reply = entry["replies"].get(timeout=timeout)
    except (OSError, ValueError, queue.Empty):
        reply = None
    if reply is None:
        _retire(entry)
        return None
    kind, data = reply
    if kind != b"blob":
        return None  # "missing", "ambiguous" or not a file: git show says why
    return subprocess.CompletedProcess(["git", "-C", str(root), "show", spec], 0, data, b"")


def _batch_reader(proc, replies):
    """Read `cat-file --batch` replies into `replies`: (type, content) for each, (b"missing", b"") for a name it
    cannot read, and None, ending, at end of output or a reply shorter than the size its header announced."""
    try:
        while True:
            header = proc.stdout.readline()
            if not header.endswith(b"\n"):
                break
            parts = header.split()
            if len(parts) == 3 and parts[2].isdigit():
                size = int(parts[2])
                data = proc.stdout.read(size + 1)
                if len(data) != size + 1 or not data.endswith(b"\n"):
                    break
                replies.put((parts[1], data[:-1]))
            else:
                replies.put((b"missing", b""))
    except (OSError, ValueError):
        pass
    replies.put(None)


def _retire(entry):
    """Stop a batch process that failed a reply: every later read in the call goes to git itself."""
    entry["broken"] = True
    proc = entry["proc"]
    proc.kill()  # unhealthy: no graceful close, which a stalled process would not answer
    proc.wait()
    proc.stdout.close()
    entry["reader"].join(timeout=10)


def _stop_batch(entry):
    proc = entry["proc"]
    try:
        proc.stdin.close()
        proc.wait(timeout=10)
    except (OSError, ValueError, subprocess.TimeoutExpired):
        proc.kill()
        proc.wait()
    finally:
        proc.stdout.close()
        entry["reader"].join(timeout=10)


def _from_history(root, older, newer, timeout):
    """`merge-base --is-ancestor older newer` from the parents of every commit the repository's refs reach, read once
    per graph call; None (run git itself) when either is not a full commit name in that history."""
    history = _RUN_CACHE["history"].get(str(root))
    if history is None:
        listed = subprocess.run(["git", "-C", str(root), "rev-list", "--parents", "--all", "HEAD"],
                                capture_output=True, timeout=timeout)
        history = {}
        if listed.returncode == 0:
            for line in listed.stdout.decode("ascii", "replace").splitlines():
                sha, *parents = line.split()
                history[sha] = parents
        _RUN_CACHE["history"][str(root)] = history
    if newer == "HEAD":
        head = _git(root, "rev-parse", "HEAD", timeout=timeout)
        newer = head.stdout.decode("ascii", "replace").strip() if head.returncode == 0 else newer
    if older not in history or newer not in history:
        return None
    seen, stack = set(), [newer]
    while stack:
        sha = stack.pop()
        if sha == older:
            return subprocess.CompletedProcess(["git", "merge-base", "--is-ancestor", older, newer], 0, b"", b"")
        if sha not in seen:
            seen.add(sha)
            stack.extend(history.get(sha, ()))
    return subprocess.CompletedProcess(["git", "merge-base", "--is-ancestor", older, newer], 1, b"", b"")


def _end_run(cache):
    """Close the graph call's `cat-file --batch` processes; one that does not stop is killed, so none outlives it."""
    for entry in cache["batch"].values():
        if not entry["broken"]:
            _stop_batch(entry)


def is_ancestor(root, older, newer):
    """True when commit `older` is `newer` or an ancestor of it."""
    return _git(root, "merge-base", "--is-ancestor", older, newer).returncode == 0


def changed_paths(root, base, candidate, ref):
    """The files that differ between two commits, repository-relative with forward slashes: what the dispatcher gave
    a three-pass pass's conditional lenses."""
    shown = _git(root, "-c", "core.quotepath=false", "diff", "--name-only", "--no-renames", "-z", base, candidate)
    require(shown.returncode == 0, f"cannot list the files changed between {base} and {candidate}: {ref}")
    return [name for name in shown.stdout.decode("utf-8", errors="replace").split("\0") if name]


def receipt_digest(data):
    """The SHA-256 of a receipt's content, independent of key order, spacing and line endings."""
    return hashlib.sha256(json.dumps(data, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


def _frozen(root, key):
    """ref -> digest under `key` in LEGACY_RECEIPTS ("receipts" or "before_plan"); empty when the file or key is absent."""
    shown = f"{receipts_folder(root)}/{LEGACY_RECEIPTS}"
    path = Path(root) / shown
    if not path.is_file():
        return {}
    try:
        data = json.loads(read_text(path))
    except ValueError:
        raise Refused(f"{shown} is not JSON") from None
    ok = isinstance(data, dict) and data.get("schema_version") == 1 and "receipts" in data
    maps = {name: data.get(name, {}) for name in ("receipts", "before_plan")} if ok else {}
    require(ok and all(isinstance(m, dict) and all(
        isinstance(k, str) and isinstance(v, str) and re.fullmatch(r"[0-9a-f]{64}", v) for k, v in m.items())
        for m in maps.values()),
            f"{shown} needs schema_version 1 and receipts (and any before_plan) mapping each ref to a "
            f"SHA-256 digest")
    return maps[key]


ADOPTED_KEYS = {"commit", "phase", "body", "receipt", "review"}


def adopted_stamps(root):
    """(marker, ref -> entry) from LEGACY_RECEIPTS's `adoption` and `adopted` keys (D03 T01 §9): the stamps a project
    made under its own tooling, frozen once at adoption by the digests of their bodies and receipts. (None, {}) when
    the project never adopted."""
    shown = f"{receipts_folder(root)}/{LEGACY_RECEIPTS}"
    path = Path(root) / shown
    if not path.is_file():
        return None, {}
    _frozen(root, "receipts")  # the file's own shape first
    data = json.loads(read_text(path))
    marker, entries = data.get("adoption"), data.get("adopted", {})
    hexes = re.compile(r"[0-9a-f]{40}")
    require(marker is None or (isinstance(marker, dict) and set(marker) == {"commit", "date"}
                               and hexes.fullmatch(str(marker["commit"]))
                               and re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(marker["date"]))),
            f"{shown}: adoption must name the commit and the date it ran")
    require(isinstance(entries, dict) and (marker is not None or not entries)
            and all(re.fullmatch(r"D\d{2} T\d{2} §[1-9]\d*", ref) and isinstance(e, dict) and set(e) == ADOPTED_KEYS
                    and hexes.fullmatch(str(e["commit"])) and isinstance(e["phase"], int)
                    and not isinstance(e["phase"], bool) and re.fullmatch(r"[0-9a-f]{64}", str(e["body"]))
                    and (e["receipt"] is None) == (e["review"] is None)
                    and (e["receipt"] is None or re.fullmatch(r"[0-9a-f]{64}", str(e["receipt"])))
                    for ref, e in entries.items()),
            f"{shown}: adopted must map each section to its commit, phase, body digest and receipt, under an adoption")
    return marker, entries


def _digest(data):
    return hashlib.sha256(data if isinstance(data, bytes) else data.encode("utf-8")).hexdigest()


def adopted_unchanged(root, entry, body):
    """Whether an adopted section's body, and the receipt it recorded, are as they were at adoption."""
    if _digest(body) != entry["body"]:
        return False
    if entry["review"] is None:
        return True
    path = Path(root) / entry["review"]
    return path.is_file() and not path.is_symlink() and _digest(path.read_bytes()) == entry["receipt"]


